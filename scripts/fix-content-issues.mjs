function yamlFiles(dir, acc = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) yamlFiles(p, acc);
    else if (name.endsWith('.yaml')) acc.push(p);
  }
  return acc;
}

let filesChanged = 0;
const done = new Set();
const problems = [];

for (const file of yamlFiles('data/tasks')) {
  const original = readFileSync(file, 'utf-8');

  // Блоки заданий начинаются со строки «- id:». Разделяем по ним же, как в
  // fix-key-conflicts: поиск через regexp с \s* захватывал перевод строки перед
  // блоком, и граница блока съезжала.
  const parts = original.split(/(?=\n- id: )/);
  let src = parts[0];
  let fileChanged = false;

  for (let i = 1; i < parts.length; i++) {
    let block = parts[i];
    const id = block.match(/^\s*- id:\s*(\S+)/)?.[1];
    const pairs = id ? REPL[id] : null;
    if (!id || !pairs) {
      src += block;
      continue;
    }
    let touched = false;
    let already = 0;
    for (const [from, to] of pairs) {
      const hits = block.split(from).length - 1;
      if (hits !== 1) {
        // скрипт одноразовый, но повторный прогон не должен падать: если новый
        // текст уже стоит, считаем подмену выполненной
        if (block.includes(to)) {
          already++;
          continue;
        }
        problems.push(`${id}: фрагмент встречается ${hits} раз -> ${from.slice(0, 60)}`);
        continue;
      }
      block = block.replace(from, to);
      touched = true;
    }
    if (touched) {
      done.add(id);
      fileChanged = true;
    } else if (already === pairs.length) {
      done.add(id);
    }
    src += block;
  }

  if (fileChanged) writeFileSync(file, src, 'utf-8');
  if (fileChanged) filesChanged++;
}

console.log(`заданий исправлено: ${done.size} из ${Object.keys(REPL).length}`);
console.log(`файлов изменено: ${filesChanged}`);
const miss = Object.keys(REPL).filter((id) => !done.has(id));
if (miss.length) console.error(`НЕ ИСПРАВЛЕНЫ: ${miss.join(', ')}`);
for (const p of problems) console.error(`! ${p}`);
process.exit(miss.length || problems.length ? 1 : 0);