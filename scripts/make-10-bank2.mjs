let checks = 0;
function ok(cond, msg) {
  checks++;
  if (!cond) throw new Error(`ASSERT FAIL: ${msg}`);
}
function eq(got, want, msg) {
  checks++;
  if (got !== want) {
    throw new Error(`ASSERT FAIL: ${msg}: получено ${JSON.stringify(got)}, ожидалось ${JSON.stringify(want)}`);
  }
}

