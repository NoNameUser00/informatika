const ALPHABET = '0123456789ABCDEF';
function parseBase(s, base) {
  const t = String(s).trim().toUpperCase();
  if (!t) return NaN;
  const valid = ALPHABET.slice(0, base);
  let v = 0;
  for (const ch of t) {
    if (!valid.includes(ch)) return NaN;
    v = v * base + valid.indexOf(ch);
  }
  return v;
}
/** Запись неотрицательного целого в основании base. */
function toBase(n, base) {
  ok(Number.isInteger(n) && n >= 0, `toBase: нужно неотрицательное целое, получено ${n}`);
  if (n === 0) return '0';
  let out = '';
  let v = n;
  while (v > 0) {
    out = ALPHABET[v % base] + out;
    v = Math.floor(v / base);
  }
  return out;
}
/** i, для которого 2^i = n; если n не степень двойки — падает. */
function log2(n) {
  let i = 0;
  while (2 ** i < n) i++;
  eq(2 ** i, n, `${n} не степень двойки — формула 2^i = N неприменима`);
  return i;
}
/** Минимальное число бит, в которое укладывается n (ceil(log2(n))). */
function bitLen(n) {
  ok(Number.isInteger(n) && n > 0, `bitLen: нужно положительное целое, получено ${n}`);
  let i = 0;
  while (2 ** i < n) i++;
  return i;
}
/** Число единиц в двоичной записи числа. */
function popcount(n) {
  let c = 0;
  let v = n;
  while (v > 0) {
    c += v & 1;
    v = Math.floor(v / 2);
  }
  return c;
}
/**
 * Периодическая дробь: первые n цифр и длина периода (0 — запись конечна).
 * Дробь задаётся точно как num/den, поэтому умножение на основание идёт
 * в целых числах: числа с плавающей точкой «ломают» поиск повтора.
 */
function fracBits(num, den, base, n) {
  ok(Number.isInteger(num) && Number.isInteger(den) && den > 0 && num >= 0, `fracBits: некорректная дробь ${num}/${den}`);
  const seen = new Map();
  const digits = [];
  let a = num;
  let b = den;
  let period = 0;
  let pre = 0;
  for (let i = 0; i < n; i++) {
    if (seen.has(a)) {
      period = i - seen.get(a);
      pre = seen.get(a);
      break;
    }
    seen.set(a, i);
    const p = a * base;
    const d = Math.floor(p / b);
    a = p - d * b;
    digits.push(d);
    if (a === 0) break;
  }
  return { digits, period, pre };
}
/** Условие Фано: ни одно кодовое слово не является началом другого. */
function fanoOk(words) {
  for (const a of words) {
    for (const b of words) {
      if (a !== b && b.startsWith(a)) return false;
    }
  }
  return true;
}
/** Префиксный декодер: пары [символ, код], разбор слева направо однозначный. */
function fanoDecode(pairs, bits) {
  const words = pairs.map(([, code]) => code);
  ok(fanoOk(words), 'код нарушает условие Фано');
  const out = [];
  let i = 0;
  while (i < bits.length) {
    const hit = pairs.find(([, code]) => bits.startsWith(code, i));
    ok(!!hit, `не разбирается остаток ${bits.slice(i)}`);
    out.push(hit[0]);
    i += hit[1].length;
  }
  ok(i === bits.length, 'сообщение не разобрано до конца');
  return out.join('');
}

// ─────────────────────────────────────────────────────────────────────────────
// Алгебра логики: разбор выражений перебором. Приоритет как в make-10-bank.mjs:
// скобки, ¬, ∧, ∨ и ⊕, → и ↔.
// ─────────────────────────────────────────────────────────────────────────────
function parseLogic(src) {
  const s = src.replace(/\s+/g, '');
  let i = 0;
  const peek = () => s[i];
  const eat = (ch) => {
    ok(s[i] === ch, `ожидался «${ch}» в выражении ${src}`);
    i++;
  };
  function parseEqv() {
    let left = parseImp();
    while (peek() === '↔') {
      i++;
      const right = parseImp();
      const l = left;
      left = (e) => (l(e) === right(e) ? 1 : 0);
    }
    return left;
  }
  function parseImp() {
    let left = parseXor();
    while (peek() === '→') {
      i++;
      const right = parseXor();
      const l = left;
      left = (e) => (!(l(e) && !right(e)) ? 1 : 0);
    }
    return left;
  }
  function parseXor() {
    let left = parseOr();
    while (peek() === '⊕') {
      i++;
      const right = parseOr();
      const l = left;
      left = (e) => (l(e) !== right(e) ? 1 : 0);
    }
    return left;
  }
  function parseOr() {
    let left = parseAnd();
    while (peek() === '∨') {
      i++;
      const right = parseAnd();
      const l = left;
      left = (e) => (l(e) || right(e) ? 1 : 0);
    }
    return left;
  }
  function parseAnd() {
    let left = parseNot();
    while (peek() === '∧') {
      i++;
      const right = parseNot();
      const l = left;
      left = (e) => (l(e) && right(e) ? 1 : 0);
    }
    return left;
  }
  function parseNot() {
    if (peek() === '¬') {
      i++;
      const x = parseNot();
      return (e) => (x(e) ? 0 : 1);
    }
    return parsePrim();
  }
  function parsePrim() {
    if (peek() === '(') {
      i++;
      const x = parseEqv();
      eat(')');
      return x;
    }
    const ch = s[i];
    if (ch === '0' || ch === '1') {
      i++;
      const c = Number(ch);
      return () => c;
    }
    ok(!!ch && /[A-Z]/.test(ch), `непонятный символ «${ch}» в выражении ${src}`);
    i++;
    return (e) => e[ch];
  }
  const fn = parseEqv();
  ok(i === s.length, `лишний хвост в выражении ${src}`);
  return fn;
}
const varsOf = (str) => [...new Set(str.match(/[A-Z]/g) ?? [])].sort();
function eachEnv(vars, fn) {
  const out = [];
  for (let mask = 0; mask < 2 ** vars.length; mask++) {
    const env = {};
    vars.forEach((v, k) => {
      env[v] = (mask >> (vars.length - 1 - k)) & 1;
    });
    out.push(fn(env));
  }
  return out;
}
const varsBoth = (a, b) => [...new Set([...varsOf(a), ...varsOf(b)])].sort();
/** Таблица истинности: строки 000, 001, … последняя буква меняется быстрее. */
function rowsOf(str) {
  const fn = parseLogic(str);
  const vars = varsOf(str);
  const rows = eachEnv(vars, (env) => ({
    env,
    text: vars.map((v) => `${v} = ${env[v]}`).join(', '),
    v: fn(env),
  }));
  return { vars, rows };
}
const evalAt = (str, env) => parseLogic(str)(env);
/** Равносильность: проверка перебором всех наборов значений. */
function equivalent(a, b) {
  const vars = varsBoth(a, b);
  return eachEnv(vars, (env) => parseLogic(a)(env) === parseLogic(b)(env)).every(Boolean);
}
/** Перфектная ДНФ по строкам единиц. */
function dnf(str) {
  const { vars, rows } = rowsOf(str);
  const ones = rows.filter((r) => r.v === 1);
  ok(ones.length > 0, `${str}: нет единиц, ДНФ не строится`);
  return ones.map((r) => `(${vars.map((v) => (r.env[v] ? v : `¬${v}`)).join(' ∧ ')})`).join(' ∨ ');
}
/** Перфектная КНФ по строкам нулей. */
function knf(str) {
  const { vars, rows } = rowsOf(str);
  const zeros = rows.filter((r) => r.v === 0);
  ok(zeros.length > 0, `${str}: нет нулей, КНФ не строится`);
  return zeros.map((r) => `(${vars.map((v) => (r.env[v] ? `¬${v}` : v)).join(' ∨ ')})`).join(' ∧ ');
}
/** Решения уравнения «выражение = значение». */
function solve(str, target) {
  return rowsOf(str).rows.filter((r) => r.v === target).map((r) => r.text);
}
const onesCount = (str) => rowsOf(str).rows.filter((r) => r.v === 1).length;

