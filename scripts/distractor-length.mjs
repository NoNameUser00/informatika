// Измерение «выдаёт ли верный вариант себя длиной».
//
// Живёт отдельно от make-distractor-review.mjs, потому что тому нельзя импортировать
// без побочных эффектов: он пишет и чистит листы в docs/review/distractors. Тест
// проверяет именно эти три функции, поэтому предмет вынесен и импортируется.
//
// Смысл каждой функции:
//
//   len            — длина видимого ученику текста: схлопнутые пробелы и обрезанные
//                    края. «24 строк» и «24  строк» должны считаться одинаково.
//   isNumericLike  — «в варианте есть цифра и нет букв». Такие варианты из
//                    ведомости исключаются: длина у чисел ничего не выдаёт.
//                    Здесь важно, чтобы буквы ВСЕХ алфавитов считались буквами.
//   giveawayPct    — запас в процентах: насколько верный вариант длиннее второго
//                    по длине. Отрицательное значение означает, что верный вариант
//                    короче всех, — это тоже подсказка, но другого рода.
export const len = (s) => String(s ?? '').replace(/\s+/g, ' ').trim().length;

export const flat = (s) => String(s ?? '').replace(/\s+/g, ' ').trim();

/**
 * Вариант — просто число?
 *
 * Прежняя запись была /^[\W\d]*\d[\W\d]*$/ и опиралась на \W. В JavaScript \w —
 * это только [A-Za-z0-9_]: кириллических букв там нет, и \W считает их
 * «не-символом слова». Из-за этого вариант «24 строк, и учебный текст читается
 * легче» проходил как число, и задание молча выпадало из ведомости: на одном
 * банке это стоило четырёх заданий, в том числе inf-10-media-043 с запасом
 * +69 %. Проверять надо именно «есть буквы или нет», а не «какой это класс
 * символов в \w».
 */
export const isNumericLike = (s) => {
  const t = String(s ?? '').trim();
  return /\d/.test(t) && !/\p{L}/u.test(t);
};

/**
 * Запас длины в процентах для одного задания.
 * Возвращает { pct, margin, mine, second } либо null, если мерить нечего.
 */
export function giveawayPct(options, answer) {
  const opt = options.find((o) => String(o.id) === String(answer));
  if (!opt) return null;
  const others = options.filter((o) => String(o.id) !== String(opt.id));
  if (!others.length) return null;
  const second = Math.max(...others.map((o) => len(o.text)));
  const mine = len(opt.text);
  return {
    pct: second ? Math.round(((mine - second) / second) * 100) : 999,
    margin: mine - second,
    mine,
    second,
  };
}