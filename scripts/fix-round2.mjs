function yamlFiles(dir, acc = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) yamlFiles(p, acc);
    else if (name.endsWith('.yaml')) acc.push(p);
  }
  return acc;
}

const doneKeys = new Set();
const doneText = new Set();
const problems = [];
let filesChanged = 0;

for (const file of yamlFiles('data/tasks')) {
  const original = readFileSync(file, 'utf-8');
  const parts = original.split(/(?=\n- id: )/);
  let out = parts[0];
  let fileChanged = false;

  for (let i = 1; i < parts.length; i++) {
    let block = parts[i];
    const id = block.match(/^\s*- id:\s*(\S+)/)?.[1];
    if (!id) {
      out += block;
      continue;
    }
    let touched = false;

    // 1) ключ
    if (id in KEYS) {
      const want = KEYS[id];
      const re = /(teacher_only:\s*\{[^}]*?\banswer:\s*)("?)([A-D])\2/;
      const cur = block.match(re)?.[3];
      if (cur === undefined) {
        problems.push(`${id}: не найден answer`);
      } else if (cur !== want) {
        block = block.replace(re, `$1$2${want}$2`);
        touched = true;
      }
      doneKeys.add(id);
    }

    // 2) текстовые правки. Меняем все вхождения: у matching подписи вариантов
    //    повторяются ещё и в answerMap, и там обязаны совпадать.
    for (const [from, to] of TEXT[id] ?? []) {
      const hits = block.split(from).length - 1;
      if (hits > 0) {
        block = block.split(from).join(to);
        touched = true;
      } else if (!block.includes(to)) {
        problems.push(`${id}: не найдено -> ${from.slice(0, 55)}`);
      }
    }
    if (id in TEXT) doneText.add(id);

    if (touched) fileChanged = true;
    out += block;
  }

  if (fileChanged) {
    writeFileSync(file, out, 'utf-8');
    filesChanged++;
  }
}

const missKeys = Object.keys(KEYS).filter((k) => !doneKeys.has(k));
const missText = Object.keys(TEXT).filter((k) => !doneText.has(k));
console.log(`ключей обработано: ${doneKeys.size} из ${Object.keys(KEYS).length}`);
console.log(`текстовых правок обработано: ${doneText.size} из ${Object.keys(TEXT).length}`);
console.log(`файлов изменено: ${filesChanged}`);
if (missKeys.length) console.error(`НЕ НАЙДЕНЫ (ключи): ${missKeys.join(', ')}`);
if (missText.length) console.error(`НЕ НАЙДЕНЫ (текст): ${missText.join(', ')}`);
for (const p of problems) console.error(`! ${p}`);
process.exit(missKeys.length || missText.length || problems.length ? 1 : 0);