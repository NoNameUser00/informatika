const ALPHABET = '0123456789ABCDEF';
function parseBase(s, base) {
  const t = String(s).trim().toUpperCase();
  if (!t) return NaN;
  const valid = ALPHABET.slice(0, base);
  let v = 0;
  for (const ch of t) {
    if (!valid.includes(ch)) return NaN;
    v = v * base + valid.indexOf(ch);
  }
  return v;
}
/** Запись целого числа в основании base — тем же алфавитом, что и parseBase. */
function toBase(n, base) {
  ok(Number.isInteger(n) && n >= 0, `toBase: нужно неотрицательное целое, получено ${n}`);
  if (n === 0) return '0';
  let out = '';
  let v = n;
  while (v > 0) {
    out = ALPHABET[v % base] + out;
    v = Math.floor(v / base);
  }
  return out;
}
/** Целая степень двойки: возвращает показатель, иначе падает. */
function log2(n) {
  let i = 0;
  while (2 ** i < n) i++;
  eq(2 ** i, n, `${n} не степень двойки — формула 2^i = N неприменима`);
  return i;
}
/** Число единиц в двоичной записи числа. */
function popcount(n) {
  let c = 0;
  let v = n;
  while (v > 0) {
    c += v & 1;
    v = Math.floor(v / 2);
  }
  return c;
}
/** Периодическая дробь: возвращает первые n цифр и длину периода (0 — конечная). */
function fracBits(frac, base, n) {
  const seen = new Map();
  const digits = [];
  let f = frac;
  let period = 0;
  for (let i = 0; i < n; i++) {
    if (seen.has(f)) {
      period = i - seen.get(f);
      break;
    }
    seen.set(f, i);
    const p = f * base;
    const d = Math.floor(p);
    f = p - d;
    digits.push(d);
    if (f === 0) break;
  }
  return { digits, period };
}
/** Условие Фано: ни одно кодовое слово не является началом другого. */
function fanoOk(words) {
  for (const a of words) {
    for (const b of words) {
      if (a !== b && b.startsWith(a)) return false;
    }
  }
  return true;
}
/** Префиксный декодер: сообщение разбирается слева направо однозначно. */
function fanoDecode(words, bits) {
  ok(fanoOk(words), 'код нарушает условие Фано');
  const out = [];
  let i = 0;
  while (i < bits.length) {
    const hit = words.find((w) => bits.startsWith(w, i));
    ok(!!hit, `не разбирается остаток ${bits.slice(i)}`);
    out.push(hit[0]);
    i += hit.length;
  }
  ok(i === bits.length, 'сообщение не разобрано до конца');
  return out.join('');
}

