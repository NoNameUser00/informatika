const DIFF_KEYS = ['basic', 'intermediate', 'advanced'];
let total = 0;
for (const b of BANKS) {
  const ids = emit(b);
  total += ids.length;
  const byLesson = new Map();
  for (const t of b.tasks) {
    const row = byLesson.get(t.lesson) ?? [0, 0, 0];
    row[DIFF_KEYS.indexOf(t.d)] += 1;
    byLesson.set(t.lesson, row);
  }
  for (const [lesson, row] of byLesson) {
    const want = PLAN[lesson];
    ok(!!want, `урок ${lesson} отсутствует в плане tmp/plan-10.txt`);
    ok(
      row[0] === want[0] && row[1] === want[1] && row[2] === want[2],
      `${lesson}: получено ${row.join('/')}, а по плану нужно ${want.join('/')}`,
    );
  }
  const counts = [0, 0, 0];
  for (const t of b.tasks) counts[DIFF_KEYS.indexOf(t.d)] += 1;
  console.log(`${b.path}: +${ids.length} заданий (${ids[0]} … ${ids[ids.length - 1]}), сложности b/i/a = ${counts.join('/')}`);
}

// Каждый урок плана должен быть написан полностью.
for (const [lesson, want] of Object.entries(PLAN)) {
  const planSum = want.reduce((a, b) => a + b, 0);
  const got = BANKS.reduce((acc, b) => acc + b.tasks.filter((t) => t.lesson === lesson).length, 0);
  eq(got, planSum, `${lesson}: написано ${got} заданий вместо ${planSum}`);
}
const wantTotal = Object.values(PLAN).reduce((acc, w) => acc + w.reduce((x, y) => x + y, 0), 0);
eq(total, wantTotal, `ожидали ${wantTotal} заданий, вышло ${total}`);
eq(wantTotal, 97, 'по плану должно быть 97 заданий');
const overall = [0, 0, 0];
for (const b of BANKS) for (const t of b.tasks) overall[DIFF_KEYS.indexOf(t.d)] += 1;
console.log(`ВСЕГО ДОПИСАНО: ${total} заданий, сложности b/i/a = ${overall.join('/')}`);
