/**
 * Пишет сгенерированный блок в конец банка. Ручная часть (до MARK) не трогается,
 * нумерация продолжается с максимального существующего номера — поэтому повторный
 * запуск даёт тот же файл байт-в-байт.
 */
function emit(cfg) {
  const raw = readFileSync(cfg.path, 'utf-8');
  const eol = raw.includes('\r\n') ? '\r\n' : '\n';
  const cut = raw.indexOf(MARK);
  const prefix = (cut === -1 ? raw : raw.slice(0, cut)).replace(/\s+$/, '');
  const nums = [...prefix.matchAll(new RegExp(`^- id: ${cfg.prefix}-(\\d+)$`, 'gm'))].map((m) => Number(m[1]));
  ok(nums.length > 0, `${cfg.path}: не найдено существующих id ${cfg.prefix}-NNN`);
  let next = Math.max(...nums) + 1;
  const used = new Set(nums.map((x) => `${cfg.prefix}-${String(x).padStart(3, '0')}`));
  const head = [];
  const body = cfg.tasks
    .map((t) => {
      const id = `${cfg.prefix}-${String(next++).padStart(3, '0')}`;
      ok(!used.has(id), `id ${id} уже занят в ${cfg.path}`);
      used.add(id);
      head.push(id);
      return [
        `- id: ${id}`,
        '  class: 10',
        `  topic: ${ys(cfg.topic)}`,
        `  subtopic: ${ys(t.sub)}`,
        `  type: ${t.type}`,
        `  difficulty: ${t.d}`,
        `  cognitive_level: ${DIFF[t.d].cog}`,
        `  points: ${DIFF[t.d].pts}`,
        `  lesson: ${t.lesson}`,
        `  fgos_requirement: ${t.req}`,
        `  fgos_element: ${t.el}`,
        `  fgos: { subject: [${t.subj}], meta: [${t.meta ?? 'plan-actions'}] }`,
        `  prompt: ${ys(t.prompt)}`,
        `  student_view: ${t.view}`,
        `  auto_check: ${t.check}`,
        `  teacher_only: ${t.teacher}`,
      ].join(eol);
    })
    .join(eol + eol);
  const text = [
    prefix,
    MARK,
    '# Ответы посчитаны кодом (parseBase, popcount, rowsOf, equivalent, dnf, knf, solve)',
    '# и проверены assert-ами: если число или формула не сошлись, сборка падает.',
    `# Новые id: ${head[0]} … ${head[head.length - 1]} (${head.length} заданий).`,
    body,
  ].join(eol) + eol;
  writeFileSync(cfg.path, text, 'utf-8');
  return head;
}

