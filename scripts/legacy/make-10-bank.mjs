// Алгебра логики: разбор выражений + таблица истинности перебором.
// Приоритет (по уроку 10logic-01-ops): скобки, ¬, ∧, ∨ и ⊕, → и ↔.
// ===========================================================================
function parseLogic(src) {
  const s = src.replace(/\s+/g, '');
  let i = 0;
  const peek = () => s[i];
  const eat = (ch) => {
    ok(s[i] === ch, `ожидался «${ch}» в выражении ${src}`);
    i++;
  };
  function parseEqv() {
    let left = parseImp();
    while (peek() === '↔') {
      i++;
      const right = parseImp();
      const l = left;
      left = (e) => (l(e) === right(e) ? 1 : 0);
    }
    return left;
  }
  function parseImp() {
    let left = parseXor();
    while (peek() === '→') {
      i++;
      const right = parseXor();
      const l = left;
      left = (e) => (!(l(e) && !right(e)) ? 1 : 0);
    }
    return left;
  }
  function parseXor() {
    let left = parseOr();
    while (peek() === '⊕') {
      i++;
      const right = parseOr();
      const l = left;
      left = (e) => (l(e) !== right(e) ? 1 : 0);
    }
    return left;
  }
  function parseOr() {
    let left = parseAnd();
    while (peek() === '∨') {
      i++;
      const right = parseAnd();
      const l = left;
      left = (e) => (l(e) || right(e) ? 1 : 0);
    }
    return left;
  }
  function parseAnd() {
    let left = parseNot();
    while (peek() === '∧') {
      i++;
      const right = parseNot();
      const l = left;
      left = (e) => (l(e) && right(e) ? 1 : 0);
    }
    return left;
  }
  function parseNot() {
    if (peek() === '¬') {
      i++;
      const x = parseNot();
      return (e) => (x(e) ? 0 : 1);
    }
    return parsePrim();
  }
  function parsePrim() {
    if (peek() === '(') {
      i++;
      const x = parseEqv();
      eat(')');
      return x;
    }
    const ch = s[i];
    if (ch === '0' || ch === '1') {
      i++;
      const c = Number(ch);
      return () => c;
    }
    ok(!!ch && /[A-Z]/.test(ch), `непонятный символ «${ch}» в выражении ${src}`);
    i++;
    return (e) => e[ch];
  }
  const fn = parseEqv();
  ok(i === s.length, `лишний хвост в выражении ${src}`);
  return fn;
}
const varsOf = (str) => [...new Set(str.match(/[A-Z]/g) ?? [])].sort();
function eachEnv(vars, fn) {
  const out = [];
  for (let mask = 0; mask < 2 ** vars.length; mask++) {
    const env = {};
    vars.forEach((v, k) => {
      env[v] = (mask >> (vars.length - 1 - k)) & 1;
    });
    out.push(fn(env));
  }
  return out;
}
const varsBoth = (a, b) => [...new Set([...varsOf(a), ...varsOf(b)])].sort();
/** Таблица истинности: строки в порядке 000, 001, … последняя буква меняется быстрее. */
function rowsOf(str) {
  const fn = parseLogic(str);
  const vars = varsOf(str);
  const rows = eachEnv(vars, (env) => ({
    env,
    text: vars.map((v) => `${v} = ${env[v]}`).join(', '),
    v: fn(env),
  }));
  return { vars, rows };
}
const evalAt = (str, env) => parseLogic(str)(env);
/** Равносильность двух выражений: проверка перебором всех наборов значений. */
function equivalent(a, b) {
  const vars = varsBoth(a, b);
  return eachEnv(vars, (env) => parseLogic(a)(env) === parseLogic(b)(env)).every(Boolean);
}
/** Перфектная ДНФ по строкам единиц. */
function dnf(str) {
  const { vars, rows } = rowsOf(str);
  const ones = rows.filter((r) => r.v === 1);
  ok(ones.length > 0, `${str}: нет единиц, ДНФ не строится`);
  return ones.map((r) => `(${vars.map((v) => (r.env[v] ? v : `¬${v}`)).join(' ∧ ')})`).join(' ∨ ');
}
/** Перфектная КНФ по строкам нулей. */
function knf(str) {
  const { vars, rows } = rowsOf(str);
  const zeros = rows.filter((r) => r.v === 0);
  ok(zeros.length > 0, `${str}: нет нулей, КНФ не строится`);
  return zeros.map((r) => `(${vars.map((v) => (r.env[v] ? `¬${v}` : v)).join(' ∨ ')})`).join(' ∧ ');
}
/** Решения уравнения «выражение = значение». */
function solve(str, target) {
  return rowsOf(str).rows.filter((r) => r.v === target).map((r) => r.text);
}
const onesCount = (str) => rowsOf(str).rows.filter((r) => r.v === 1).length;

