const ORDER = ['class', 'topic', 'subtopic', 'type', 'difficulty', 'cognitive_level', 'points',
  'lesson', 'fgos_requirement', 'fgos_element', 'fgos', 'prompt', 'student_view', 'auto_check', 'teacher_only'];
if (ORDER.length !== 15) throw new Error('ORDER разъехался');

/**
 * Любой маркер make-7-bank2 (в т.ч. оставшийся от параллельного запуска
 * с другим суффиксом) — режется, чтобы в банке остался ровно один
 * сгенерированный блок и квота tmp/need-7.txt не удваивалась.
 */
const ANY_MARK = /^# ==== СГЕНЕРИРОВАНО scripts\/make-7-bank2\.mjs[^\n]*====$/gm;

/** Читает банк, отбрасывая ранее сгенерированные этим скриптом блоки. */
function readHead(file) {
  const raw = readFileSync(file, 'utf-8');
  const hits = [...raw.matchAll(ANY_MARK)];
  const at = hits.length ? hits[0].index : -1;
  const head = (at === -1 ? raw : raw.slice(0, at)).replace(/\s+$/, '');
  return { head, staleBlocks: hits.length };
}

function maxId(head, prefix) {
  let max = 0;
  for (const m of head.matchAll(new RegExp(`- id: ${prefix.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}(\\d{3})`, 'g')))
    max = Math.max(max, Number(m[1]));
  return max;
}

function yamlBlock(t) {
  const fields = {
    class: '7',
    // topic и subtopic всегда в кавычках: значение с двоеточием иначе ломает YAML.
    topic: q(t.topic),
    subtopic: q(t.sub),
    type: t.type,
    difficulty: t.diff,
    cognitive_level: t.cog,
    points: t.points,
    lesson: t.lesson,
    fgos_requirement: '1.1',
    fgos_element: '1.1',
    fgos: `{ subject: [${t.subj}], meta: [plan-actions] }`,
    prompt: q(t.prompt),
    student_view: t.sv,
    auto_check: t.ac,
    teacher_only: t.to,
  };
  for (const k of ORDER) {
    if (fields[k] === undefined) throw new Error(`нет поля ${k} у ${t.id}`);
  }
  return [`- id: ${t.id}`, ...ORDER.map((k) => `  ${k}: ${fields[k]}`)].join('\n');
}

const allIds = new Set();
const perLesson = new Map();

for (const bank of Object.keys(FILES)) {
  const { file, prefix } = FILES[bank];
  const { head, staleBlocks } = readHead(file);
  for (const m of head.matchAll(/- id: (\S+)/g)) {
    if (allIds.has(m[1])) throw new Error(`id ${m[1]} уже есть в банках 7 класса`);
    allIds.add(m[1]);
  }
  let next = maxId(head, prefix) + 1;
  const blocks = state[bank].map((t) => {
    const id = prefix + String(next++).padStart(3, '0');
    if (allIds.has(id)) throw new Error(`id ${id} уже занят`);
    allIds.add(id);
    const row = perLesson.get(t.lesson) ?? { basic: 0, intermediate: 0, advanced: 0 };
    row[t.diff] += 1;
    perLesson.set(t.lesson, row);
    return yamlBlock({ ...t, id });
  });
  const out = `${head}\n\n${MARK}\n`
    + '# Ответы вычислены кодом (calc/подбор варианта) и проверены check.mjs.\n\n'
    + `${blocks.join('\n\n')}\n`;
  writeFileSync(file, out, 'utf-8');
  console.log(`BANK OK: ${file} — добавлено ${blocks.length} заданий (${prefix}${String(maxId(head, prefix) + 1).padStart(3, '0')}-${String(next - 1).padStart(3, '0')})${staleBlocks ? ` [перезаписан старый блок: ${staleBlocks}]` : ''}`);
}

