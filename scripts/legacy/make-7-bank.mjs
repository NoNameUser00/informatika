const ORDER = ['class', 'topic', 'subtopic', 'type', 'difficulty', 'cognitive_level', 'points',
  'lesson', 'fgos_requirement', 'fgos_element', 'fgos', 'prompt', 'student_view', 'auto_check', 'teacher_only'];
if (ORDER.length !== 15) throw new Error('ORDER разъехался');

/** Читает банк, отбрасывая ранее сгенерированный блок. */
function readHead(file) {
  const raw = readFileSync(file, 'utf-8');
  const at = raw.indexOf(MARK);
  const head = (at === -1 ? raw : raw.slice(0, at)).replace(/\s+$/, '');
  return { head, hadBlock: at !== -1 };
}

function maxId(head, prefix) {
  let max = 0;
  for (const m of head.matchAll(new RegExp(`- id: ${prefix.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}(\\d{3})`, 'g')))
    max = Math.max(max, Number(m[1]));
  return max;
}

function yamlBlock(t) {
  const L = [`- id: ${t.id}`];
  L.push('  class: 7');
  for (const k of ['topic', 'subtopic', 'type']) L.push(`  ${k}: ${plain(t[k])}`);
  L.push(`  difficulty: ${t.diff}`);
  L.push(`  cognitive_level: ${t.cog}`);
  L.push(`  points: ${t.points}`);
  L.push(`  lesson: ${t.lesson}`);
  L.push(`  fgos_requirement: ${t.req}`);
  L.push(`  fgos_element: ${t.el}`);
  L.push(`  fgos: { subject: [${t.subj}], meta: [${t.meta}] }`);
  L.push(`  prompt: ${q(t.prompt)}`);
  L.push(`  student_view: ${t.sv}`);
  L.push(`  auto_check: ${t.ac}`);
  L.push(`  teacher_only: ${t.to}`);
  return L.join('\n');
}

const allIds = new Set();
const perLesson = new Map();

for (const bank of Object.keys(FILES)) {
  const file = FILES[bank];
  const prefix = bank === 'inf' ? 'inf-7-inf-' : bank === 'base' ? 'inf-7-base-' : 'inf-7-media-';
  const { head, hadBlock } = readHead(file);
  for (const m of head.matchAll(/- id: (\S+)/g)) {
    if (allIds.has(m[1])) throw new Error(`id ${m[1]} уже есть в банках 7 класса`);
    allIds.add(m[1]);
  }
  let next = maxId(head, prefix) + 1;
  const blocks = state[bank].map((t) => {
    const id = prefix + String(next++).padStart(3, '0');
    if (allIds.has(id)) throw new Error(`id ${id} уже занят`);
    allIds.add(id);
    const row = perLesson.get(t.lesson) ?? { basic: 0, intermediate: 0, advanced: 0 };
    row[t.diff] += 1;
    perLesson.set(t.lesson, row);
    return yamlBlock({ ...t, id });
  });
  const out = `${head}\n\n${MARK}\n`
    + '# Ответы вычислены кодом (calc/автоматический подбор варианта) и проверены check.mjs.\n\n'
    + `${blocks.join('\n\n')}\n`;
  writeFileSync(file, out, 'utf-8');
  console.log(`BANK OK: ${file} — добавлено ${blocks.length} заданий (${prefix}${String(maxId(head, prefix) + 1).padStart(3, '0')}-${String(next - 1).padStart(3, '0')})${hadBlock ? ' [блок перезаписан]' : ''}`);
}

