const LETTERS = 'ABCD';

/** Строка в двойных кавычках для YAML (экранируем только \\ и "). */
const q = (s) => `"${String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;

/** Обычный скаляр YAML: допускаем только безопасный набор символов. */
function plain(s) {
  const t = String(s);
  if (/^[\s>|*&!%@`'"[\]{},#]|[:#]\s|\s$|^(---|null|true|false|yes|no|on|off)$/i.test(t)) return q(t);
  if (!/^[^\x00-\x1f]+$/.test(t)) throw new Error(`непечатный символ в «${t}»`);
  return t;
}

const state = { inf: [], base: [], media: [] };

function push(bank, o) {
  const points = { basic: 1, intermediate: 2, advanced: 3 }[o.diff];
  if (!points) throw new Error(`неизвестная сложность: ${o.diff}`);
  if (!o.cog) throw new Error(`нет cognitive_level: ${o.prompt}`);
  if (!PLAN[o.lesson]) throw new Error(`урока нет в плане: ${o.lesson}`);
  state[bank].push({
    bank, lesson: o.lesson, topic: o.topic, subtopic: o.sub, type: o.type,
    diff: o.diff, cog: o.cog, points, subj: o.subj, meta: o.meta ?? 'plan-actions',
    req: o.req ?? 1.1, el: o.el ?? 1.1,
    prompt: o.prompt, sv: o.sv, ac: o.ac, to: o.to,
  });
}

/** numeric_base: ответ считается кодом (calc) и обязан совпасть с авторским want. */
function nb(bank, o) {
  const value = o.calc();
  if (value !== o.want) throw new Error(`${bank} ${o.prompt}\n  calc() = ${value}, а в плане задания ${o.want}`);
  if (!Number.isInteger(value)) throw new Error(`${bank} ${o.prompt}: ответ не целый — ${value}`);
  const key = String(value);
  if (!/^\d+$/.test(key)) throw new Error(`${bank} ${o.prompt}: ключ «${key}» не десятичное число`);
  const base = o.base ?? 10;
  const r = checkNumericBase(value, key, base);
  if (!r.isCorrect) throw new Error(`${bank} ${o.prompt}: ключ «${key}» не сходится с ${value} в основании ${base}`);
  push(bank, {
    ...o, type: 'numeric_base',
    sv: `{ base: ${base}, placeholder: "только число" }`,
    ac: `{ method: numeric_base, base: ${base}, strip_affixes: true }`,
    to: `{ accepted_values_decimal: [${value}], answer_text: ${q(key)}, explanation: ${q(o.why)} }`,
  });
}

/** single_choice: correct задаётся ТЕКСТОМ, номер находится кодом и проверяется. */
function sc(bank, o) {
  const texts = o.opts.map((x) => String(x));
  if (texts.length < 2 || texts.length > 4) throw new Error(`${bank} ${o.prompt}: вариантов ${texts.length} (нужно 2–4)`);
  if (new Set(texts).size !== texts.length) throw new Error(`${bank} ${o.prompt}: варианты повторяются`);
  const i = texts.indexOf(String(o.correct));
  if (i < 0) throw new Error(`${bank} ${o.prompt}: правильного варианта «${o.correct}» нет среди ${JSON.stringify(texts)}`);
  push(bank, {
    ...o, type: 'single_choice',
    sv: `{ options: [${texts.map((t, k) => `{ id: ${LETTERS[k]}, text: ${q(t)} }`).join(', ')}] }`,
    ac: '{ method: exact_option }',
    to: `{ answer: ${LETTERS[i]}, explanation: ${q(o.why)} }`,
  });
}

/** matching: карта собирается из left, полный балл проверяется check.mjs. */
function mat(bank, o) {
  const left = o.left.map(String);
  if (left.length < 1) throw new Error(`${bank} ${o.prompt}: пустой столбец слева`);
  if (new Set(left).size !== left.length) throw new Error(`${bank} ${o.prompt}: левый столбец с повторами`);
  const vals = left.map((k) => {
    if (!(k in o.map)) throw new Error(`${bank} ${o.prompt}: нет ответа для «${k}»`);
    return String(o.map[k]);
  });
  if (new Set(vals).size !== vals.length) throw new Error(`${bank} ${o.prompt}: правый столбец с повторами — соответствие неоднозначно`);
  const right = [...vals];
  const points = { basic: 1, intermediate: 2, advanced: 3 }[o.diff];
  const r = checkMatching(o.map, Object.fromEntries(left.map((k, i) => [k, vals[i]])), points);
  if (!r.isCorrect || r.score !== points) throw new Error(`${bank} ${o.prompt}: соответствие не сходится (${r.score} из ${points})`);
  push(bank, {
    ...o, type: 'matching',
    sv: `{ left: [${left.map(q).join(', ')}], right: [${right.map(q).join(', ')}] }`,
    ac: '{ method: matching, partial: proportional }',
    to: `{ answer_map: { ${left.map((k, i) => `${q(k)}: ${q(vals[i])}`).join(', ')} }, explanation: ${q(o.why)} }`,
  });
}

