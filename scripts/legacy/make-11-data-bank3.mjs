/**
 * numeric_base. Значение приходит уже посчитанным (см. функции ниже),
 * answer_text — его десятичная запись, обе сверяются assert-ом.
 */
function num(o) {
  if (!Number.isInteger(o.value)) throw new Error(`${o.lesson}: ответ ${o.value} не целый`);
  if (parseInt(o.text, 10) !== o.value) throw new Error(`${o.lesson}: ответ <${o.text}> != ${o.value} [sub=${o.sub}]`);
  if (!Number.isFinite(o.value)) throw new Error(`${o.lesson}: ответ не число [sub=${o.sub}]`);
  if (!o.why) throw new Error(`${o.lesson}: нет explanation [sub=${o.sub}]`);
  const base = o.base ?? 10;
  put({
    topic: o.topic, sub: o.sub, type: 'numeric_base', d: o.d, cog: o.cog, lesson: o.lesson, subj: o.subj,
    prompt: o.prompt,
    sv: `{ base: ${base} }`,
    ac: `{ method: numeric_base, base: ${base}, strip_affixes: true }`,
    to: `{ accepted_values_decimal: [${o.value}], answer_text: ${q(o.text)}, explanation: ${q(o.why)} }`,
  });
}

/** single_choice. Правильный вариант задан текстом; буква = LETTERS[индекс]. */
function sc(o) {
  const opts = o.opts;
  if (opts.length !== 4) throw new Error(`${o.lesson}: вариантов ${opts.length}, нужно 4 [sub=${o.sub}]`);
  if (new Set(opts).size !== opts.length) throw new Error(`${o.lesson}: повторяющиеся варианты`);
  const idx = opts.indexOf(o.correctText);
  if (idx < 0) throw new Error(`${o.lesson}: правильный вариант <${o.correctText}> не среди вариантов`);
  const letter = LETTERS[idx];
  put({
    topic: o.topic, sub: o.sub, type: 'single_choice', d: o.d, cog: o.cog, lesson: o.lesson, subj: o.subj,
    prompt: o.prompt,
    sv: `{ options: [${opts.map((t, i) => `{ id: ${LETTERS[i]}, text: ${q(t)} }`).join(', ')}] }`,
    ac: `{ method: exact_option }`,
    to: `{ answer: ${q(letter)}, explanation: ${q(o.why)}${o.errors ? `, common_errors: [${o.errors.map(q).join(', ')}]` : ''} }`,
  });
  return letter;
}

/** matching. Соответствие собирается кодом: Object.fromEntries(left.map((l, i) => [l, right[i]])). */
function mt(o) {
  const map = Object.fromEntries(o.left.map((l, i) => [l, o.right[i]]));
  const vals = Object.values(map);
  if (vals.length !== o.left.length) throw new Error(`${o.lesson}: ${vals.length} пар на ${o.left.length} пунктов`);
  if (new Set(vals).size !== vals.length) throw new Error(`${o.lesson}: значения повторяются — соответствие неоднозначно`);
  for (const l of o.left) if (!map[l]) throw new Error(`${o.lesson}: нет пары для <${l}>`);
  put({
    topic: o.topic, sub: o.sub, type: 'matching', d: o.d, cog: o.cog, lesson: o.lesson, subj: o.subj,
    prompt: o.prompt,
    sv: `{ left: [${o.left.map(q).join(', ')}], right: [${o.right.map(q).join(', ')}] }`,
    ac: `{ method: matching, partial: proportional }`,
    to: `{ answer_map: { ${o.left.map((l) => `${q(l)}: ${q(map[l])}`).join(', ')} }, explanation: ${q(`${o.why} Верно: ${o.left.map((l) => `${l} = ${map[l]}`).join('; ')}.`)} }`,
  });
}

/** Гоняет solution_code локальным Python. expected_stdout = РЕАЛЬНЫЙ stdout. */
function py(code) {
  const env = { ...process.env, PYTHONIOENCODING: 'utf-8', PYTHONUTF8: '1' };
  let res;
  try {
    res = execFileSync('python3', ['-c', code], { encoding: 'utf-8', env });
  } catch {
    res = execFileSync('python', ['-c', code], { encoding: 'utf-8', env });
  }
  return String(res).replace(/\r\n/g, '\n').replace(/\n+$/, '');
}

/** code_run. Решение исполняется на генерации; stdout сверяется с ожидаемым. */
function cr(o) {
  const outp = py(o.solution);
  if (o.expected !== undefined && o.expected !== outp) {
    throw new Error(`${o.lesson}: вывод не совпал с ожиданием\nожидалось: ${JSON.stringify(o.expected)}\nполучили:  ${JSON.stringify(outp)}`);
  }
  if (!outp) throw new Error(`${o.lesson}: решение ничего не вывело`);
  put({
    topic: o.topic, sub: o.sub, type: 'code_run', d: o.d, cog: o.cog, lesson: o.lesson, subj: o.subj,
    prompt: o.prompt,
    sv: `{ language: python, template: ${q(o.template)} }`,
    ac: `{ method: code_stdout, timeout_s: 10 }`,
    to: `{ solution_code: ${q(o.solution)}, expected_stdout: ${q(outp)}, explanation: ${q(o.why)} }`,
  });
  return outp;
}

// ---------- вычислительные функции (на них же assert-ы) ----------

const sum = (a) => a.reduce((s, v) => s + v, 0);
const mean = (a) => sum(a) / a.length;

function variance(a) {
  const m = mean(a);
  return a.reduce((s, v) => s + (v - m) ** 2, 0) / a.length;
}

/** Мода набора; бросает, если максимум не единственный. */
function mode(a) {
  const cnt = new Map();
  for (const v of a) cnt.set(v, (cnt.get(v) ?? 0) + 1);
  const best = Math.max(...cnt.values());
  const top = [...cnt.entries()].filter(([, c]) => c === best);
  if (top.length !== 1) throw new Error(`мода не единственна: ${JSON.stringify(top)}`);
  return top[0][0];
}

/** Наклон линии тренда y = kx + b методом наименьших квадратов. */
function slope(x, y) {
  const mx = mean(x), my = mean(y);
  let sxy = 0, sxx = 0;
  for (let i = 0; i < x.length; i++) {
    sxy += (x[i] - mx) * (y[i] - my);
    sxx += (x[i] - mx) ** 2;
  }
  return sxy / sxx;
}

const round2 = (v) => Math.round(v * 100) / 100;
const eq = (label, got, want) => {
  const ok = typeof want === 'number' ? Math.abs(got - want) < 1e-9 : got === want;
  if (!ok) throw new Error(`assert: ${label} = ${got}, ожидалось ${want}`);
  return got;
};

