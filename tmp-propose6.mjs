const OPTION_RE = /^\*\*([A-D])\.\*\* (.*?)\s*_\(\d+ симв\.\)_$/;
const dir = 'docs/review/distractors';
let written = 0;
const problems = [];

for (const f of readdirSync(dir).filter((x) => x.endsWith('.md') && x !== 'README.md')) {
  const p = join(dir, f);
  const lines = readFileSync(p, 'utf-8').split('\n');
  let current = null;
  let changed = false;

  for (let i = 0; i < lines.length; i++) {
    const h = /^## \d+\. (\S+)/.exec(lines[i]);
    if (h) current = h[1];
    const m = OPTION_RE.exec(lines[i]);
    if (!m || !current) continue;
    const proposal = PROPOSALS[current]?.[m[1]];
    if (!proposal) continue;
    if (!/^новый текст:/.test(lines[i + 1] ?? '')) {
      problems.push(`${current} ${m[1]}: нет строки «новый текст:»`);
      continue;
    }
    lines[i + 1] = `новый текст: ${proposal}`;
    changed = true;
    written++;
  }

  if (changed) writeFileSync(p, lines.join('\n'), 'utf-8');
}

console.log(`вписано строк: ${written}`);
console.log(`заданий: ${Object.keys(PROPOSALS).length}`);
if (problems.length) for (const x of problems) console.error('  ' + x);